import test from 'node:test';
import assert from 'node:assert/strict';
import os from 'node:os';
import path from 'node:path';
import {mkdtemp,rm} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {configureExtensions} from '../lib/extensions.mjs';
import {createAppServer} from '../lib/http-app.mjs';
import {createDeviceControl} from '../lib/device-control.mjs';
import {createOperationsCore} from '../lib/operations-core.mjs';
import {createOperations} from '../lib/operations.mjs';
const appRoot=fileURLToPath(new URL('..',import.meta.url));

test('public core serves files, apps, settings and logs without OEM extensions or a real ADB process',async t=>{
  await configureExtensions({root:appRoot,enabled:[]});
  const root=await mkdtemp(path.join(os.tmpdir(),'adb-public-core-')),calls=[];
  const device={id:'TEST_DEVICE',model:'Test Android',manufacturer:'Example',transports:[{serial:'MOCK_ONLY',state:'device',type:'usb'}]};
  const readDevices=async()=>({devices:[device],services:[]}),resolve=async()=>({device,serial:'MOCK_ONLY'});
  const command=async(serial,args)=>{
    assert.equal(serial,'MOCK_ONLY');calls.push(args);
    const text=args.join(' ');
    if(text.includes('get-current-user'))return '0';
    if(text==='shell getprop ro.build.fingerprint')return 'example/test/test:17/TEST/TEST:user/release-keys';
    if(text.includes('settings --user 0 list system'))return 'screen_brightness=100\nscreen_off_timeout=30000';
    if(text.includes('settings --user 0 list secure')||text.includes('settings --user 0 list global'))return '';
    if(text.startsWith('shell pm list users'))return 'Users:\n UserInfo{0:Owner:13} running';
    if(text.startsWith('shell pm list packages'))return text.includes(' -d')?'':text.includes(' -f')?'package:/data/app/example/base.apk=org.example.notes uid:10123 versionCode:1':'package:org.example.notes';
    if(text.includes('query-activities'))return 'org.example.notes/.MainActivity';
    if(text.includes('dumpsys package packages')||text.includes('diskstats_cache.json'))return '';
    if(args[0]==='logcat')return '1700000000.123456 123 123 I Example: test log\n';
    if(args[0]==='shell'&&text.includes('find'))return 'E\0regular file|12|1700000000\0/sdcard/example.txt\0';
    throw new Error('Unexpected mock command: '+text);
  };
  const control=createDeviceControl({root,readDevices,executeCommand:command});
  const baseCore=createOperationsCore({root,adbPath:process.execPath,resolve});
  const core={...baseCore,run:async(serial,args)=>({stdout:await command(serial,args),stderr:''}),shell:async(serial,text)=>command(serial,['shell',text])};
  const server=createAppServer({root:appRoot,readDevices,deviceControl:control,adbPath:'MOCK_ONLY_NEVER_EXECUTED',operationsFactory:opts=>createOperations({...opts,core,readDevices:async()=>({devices:[],services:[]})})});
  await new Promise(resolveListen=>server.listen(0,'127.0.0.1',resolveListen));
  t.after(async()=>{server.closeAllConnections();await new Promise(resolveClose=>server.close(resolveClose));await server.cleanupPromise;await rm(root,{recursive:true,force:true});});
  const base='http://127.0.0.1:'+server.address().port;
  const get=async route=>{const response=await fetch(base+route);assert.equal(response.status,200,route);return response.json();};
  const features=await get('/api/device/features?id=TEST_DEVICE');assert.ok(Object.values(features.features).every(value=>value===false));assert.equal(features.assets.scripts.length,0);
  const settings=await get('/api/device?id=TEST_DEVICE');assert.ok(settings.settings.some(row=>row.key==='screen_brightness'));assert.ok(settings.settings.every(row=>!row.manufacturer));
  const apps=await get('/api/device/apps?id=TEST_DEVICE&user=0');assert.equal(apps.apps[0].package,'org.example.notes');
  const files=await get('/api/ops/files?deviceId=TEST_DEVICE&path=/sdcard');assert.equal(files.entries[0].name,'example.txt');
  const logs=await get('/api/ops/logs?deviceId=TEST_DEVICE');assert.equal(logs.entries[0].message,'test log');
  const before=calls.length;
  for(const route of ['/api/device/privacy-indicators?id=TEST_DEVICE','/api/device/gps-indicator?id=TEST_DEVICE&package=org.example.notes','/extensions/samsung/privacy-indicators.js'])assert.ok([404,409].includes((await fetch(base+route)).status),route);
  assert.equal(calls.length,before,'disabled extension requests may not execute ADB commands');
  const {csrfToken}=await get('/api/session');
  const headers={Origin:base,'Content-Type':'application/json','X-ADB-Desk-Token':csrfToken};
  const response=await fetch(base+'/api/device/settings',{method:'POST',headers,body:JSON.stringify({deviceId:'TEST_DEVICE',action:'set',key:'aod_mode',value:'0',expected:'1'})});assert.notEqual(response.status,200);assert.equal(calls.length,before);
  assert.ok(calls.every(args=>!args.includes('put')&&!args.includes('delete')&&!args.includes('start')&&!args.includes('grant')));
});
